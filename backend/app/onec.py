"""Общие правила чтения выгрузок 1С.

Пока здесь одно правило, но важное: непроведённый документ и документ,
помеченный на удаление, — не операция. Товар по ним не списан, долг не
возник, деньги не двигались. Если такая строка попадает в выгрузку, портал
считает её фактом: завышаются продажи, дебиторка и расход со склада.

Отсекать их должна сама обработка 1С — это дешевле и надёжнее. Но полагаться
на это целиком нельзя: обработку правят, а ошибка тихая и обнаружится через
месяц в цифрах, а не в журнале ошибок. Поэтому если в файле есть колонка
«Проведён» или «ПометкаУдаления», портал проверит её сам.
"""

# Названия колонок-признаков в разных написаниях: обработку пишут люди, и
# «Проведен»/«Проведён»/«Проведение» встречаются вперемешку.
POSTED_HEADERS = ("Проведен", "Проведён", "Проведение", "Проведенность",
                  "ДокументПроведен", "Posted")
DELETED_HEADERS = ("ПометкаУдаления", "ПометкаНаУдаление", "УдалениеПометка",
                   "DeletionMark", "Deleted")

_FALSE = {"нет", "ложь", "false", "0", "no", "n", "-"}
_TRUE = {"да", "истина", "true", "1", "yes", "y", "+"}


def _flag(value) -> bool | None:
    """Признак из ячейки 1С: True/False, «Да»/«Нет», «Истина»/«Ложь», 1/0.
    None — значение непонятное или пустое, и тогда судить не о чем."""
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    s = str(value).strip().lower()
    if not s:
        return None
    if s in _TRUE:
        return True
    if s in _FALSE:
        return False
    return None


def header_map() -> dict[str, str]:
    """Колонки-признаки → внутренние имена. Подмешивается в HEADERS импортёров;
    колонки необязательные, файлы без них грузятся как раньше."""
    out = {h: "_posted" for h in POSTED_HEADERS}
    out.update({h: "_deleted" for h in DELETED_HEADERS})
    return out


def skip_reason(data: dict) -> str | None:
    """Почему строку не берём в учёт. None — берём.

    Осторожность в обе стороны: непроведённость считаем только тогда, когда
    в ячейке однозначное «нет». Пустая ячейка ничего не значит — мало ли
    почему её не заполнили, и молча выбрасывать по ней данные нельзя."""
    if _flag(data.get("_deleted")) is True:
        return "помечен на удаление"
    if _flag(data.get("_posted")) is False:
        return "не проведён"
    return None
